export interface DatabaseCompactionResult {
  /**
   * completed: VACUUM ran. busy: the app did not become idle in time, so
   * nothing ran. insufficient-space: not enough free disk for SQLite's
   * temporary copy, so nothing ran.
   */
  status: "completed" | "busy" | "insufficient-space";
  beforeBytes: number;
  afterBytes: number;
  reclaimedBytes: number;
  checkpointBusy: boolean;
  /** Free bytes needed before compaction may start (insufficient-space). */
  requiredFreeBytes?: number;
  availableFreeBytes?: number;
}

/**
 * Disk usage of one workspace checkout, split by what can be regenerated.
 * Bytes are logical file sizes; APFS clones and hard links may share physical
 * blocks, so the sum can exceed what the disk actually allocates. Git objects
 * (`.git`) are shared between a project's worktrees and are not counted.
 */
export interface WorkspaceDiskUsage {
  projectId: string;
  projectName: string;
  path: string;
  /** Git-derived workspace label (branch or default branch for the root). */
  name: string;
  isProjectRoot: boolean;
  /** Everything not classified below: tracked and untracked user files. */
  sourceBytes: number;
  /** Package-manager output (`node_modules`, `.venv`, `Pods`, …), regenerated by an install. */
  dependencyBytes: number;
  /** Known build/tool output (`dist`, `target`, `.build`, `__pycache__`, …). */
  buildBytes: number;
  fileCount: number;
  /** The scan stopped at its entry budget; totals are lower bounds. */
  truncated: boolean;
}

export interface WorkspaceDiskUsageReport {
  workspaces: WorkspaceDiskUsage[];
  scannedAt: number;
}
